console.log(`Evaluating ${newArticles.length} new articles...`)

let allValid = true

newArticles.forEach((art, i) => {
  const sectionTexts = (art.sections || []).flatMap(s => [
    s.heading,
    s.subheading || '',
    ...s.paragraphs,
    ...(s.table ? [...s.table.headers, ...s.table.rows.flat()] : [])
  ])
  const fullText = [
    art.title,
    art.excerpt,
    ...art.highlights,
    ...art.content,
    ...sectionTexts,
    ...art.faqs.map(f => `${f.question} ${f.answer}`)
  ].join(' ')
  const words = fullText.split(/\s+/).filter(Boolean)
  const totalWords = words.length

  const titleLen = art.metaTitle.length
  const descLen = art.metaDescription.length

  const primary = art.targetKeyword
  const regexPrimary = new RegExp(primary.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&'), 'gi')
  const occurrences = (fullText.match(regexPrimary) || []).length
  const phraseWords = primary.split(/\s+/).length
  const tokenDensity = ((occurrences * phraseWords) / totalWords) * 100

  console.log(`\nArticle ${i + 10}: ${art.slug}`)
  console.log(`  Words: ${totalWords} (Target 800-1250) -> ${totalWords >= 800 && totalWords <= 1250 ? '✅' : '❌'}`)
  console.log(`  Title Len: ${titleLen} chars (Target 40-60) -> ${titleLen >= 40 && titleLen <= 60 ? '✅' : '❌'}`)
  console.log(`  Desc Len: ${descLen} chars (Target 120-160) -> ${descLen >= 120 && descLen <= 160 ? '✅' : '❌'}`)
  console.log(`  Keyword "${primary}": ${occurrences} times | Token Density: ${tokenDensity.toFixed(2)}% (Target 3-5.5%) -> ${tokenDensity >= 3.0 && tokenDensity <= 5.5 ? '✅' : '⚠️'}`)

  art.secondaryKeywords.forEach(sec => {
    const reg = new RegExp(sec.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&'), 'gi')
    const m = (fullText.match(reg) || []).length
    console.log(`    • "${sec}": ${m} occurrences -> ${m >= 2 ? '✅' : '⚠️'}`)
  })

  if (totalWords < 800 || totalWords > 1250 || titleLen < 40 || titleLen > 60 || descLen < 120 || descLen > 160 || tokenDensity < 3.0 || tokenDensity > 5.5) {
    allValid = false
  }
})

if (!allValid) {
  console.error('\n❌ Some validation checks failed! Please calibrate word counts or lengths.')
  process.exit(1)
} else {
  console.log('\n✅ All 10 articles passed validation perfectly! Updating src/data/articles.ts...')
  
  // Read current articles.ts
  const articlesFilePath = path.join(__dirname, '../src/data/articles.ts')
  let content = fs.readFileSync(articlesFilePath, 'utf8')

  const lastBracketIndex = content.lastIndexOf(']')
  if (lastBracketIndex === -1) {
    console.error('Could not find closing bracket of ARTICLES_DATA')
    process.exit(1)
  }

  const newArticlesCode = newArticles.map(art => {
    return `  {\n    id: ${JSON.stringify(art.id)},\n    slug: ${JSON.stringify(art.slug)},\n    title: ${JSON.stringify(art.title)},\n    metaTitle: ${JSON.stringify(art.metaTitle)},\n    metaDescription: ${JSON.stringify(art.metaDescription)},\n    targetKeyword: ${JSON.stringify(art.targetKeyword)},\n    secondaryKeywords: ${JSON.stringify(art.secondaryKeywords, null, 6)},\n    category: ${JSON.stringify(art.category)},\n    date: ${JSON.stringify(art.date)},\n    readTime: ${JSON.stringify(art.readTime)},\n    author: ${JSON.stringify(art.author)},\n    coverImage: ${JSON.stringify(art.coverImage)},\n    excerpt: ${JSON.stringify(art.excerpt)},\n    highlights: ${JSON.stringify(art.highlights, null, 6)},\n    content: ${JSON.stringify(art.content, null, 6)},\n    sections: ${JSON.stringify(art.sections, null, 6)},\n    faqs: ${JSON.stringify(art.faqs, null, 6)},\n    igLink: ${JSON.stringify(art.igLink)}\n  }`
  }).join(',\n\n')

  const beforeBracket = content.substring(0, lastBracketIndex).trimEnd()
  const hasTrailingComma = beforeBracket.endsWith(',')
  const separator = hasTrailingComma ? '\n\n' : ',\n\n'
  const updatedContent = `${beforeBracket}${separator}${newArticlesCode}\n]\n`

  fs.writeFileSync(articlesFilePath, updatedContent, 'utf8')
  console.log('✅ Successfully appended 10 calibrated articles to src/data/articles.ts!')
}
